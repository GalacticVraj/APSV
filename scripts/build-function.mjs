/**
 * Bundle the API into a single self-contained serverless function.
 *
 * Why bundle it here instead of letting the platform compile it
 * ------------------------------------------------------------
 * Three deployments failed in a row, each on a different part of the platform's
 * own TypeScript handling:
 *
 *   1. A dynamic `import()` of a `.ts` path was left as a literal specifier, so
 *      the function looked for TypeScript source that is never deployed
 *      (ERR_MODULE_NOT_FOUND).
 *   2. A static import fixed that, and the module then crashed while loading —
 *      reported only as FUNCTION_INVOCATION_FAILED, with no way to see why from
 *      outside.
 *   3. Which is the real problem: a crash at import cannot be caught by the
 *      module that is crashing, so no amount of error handling inside it helps.
 *
 * Every one of those was a question about how the host compiles and resolves
 * TypeScript. So this stops asking. esbuild produces one plain JavaScript file
 * with the entire engine inlined — no imports to resolve, no `.ts` specifiers,
 * no module format to negotiate. The only thing left that can fail is the code
 * itself, and that the function's own try/catch reports as JSON.
 *
 * The output is committed. A generated artefact in source control is a real
 * cost, and it is the right trade here: the alternative is a deployment whose
 * success depends on build-time behaviour we cannot observe or reproduce. It is
 * regenerated by `npm run build`, so it cannot drift from the source without
 * someone committing a stale build on purpose.
 *
 * Run directly with `node scripts/build-function.mjs`.
 */

import { build } from 'esbuild';
import { mkdirSync } from 'node:fs';

mkdirSync('api', { recursive: true });

const result = await build({
  entryPoints: ['packages/api/src/vercel-entry.ts'],
  // One plain filename. A bracketed catch-all matched /api/health but not
  // /api/carbon/history, so the route comes from an explicit rewrite instead,
  // which hands the original path over as __path for the entry to restore.
  outfile: 'api/index.js',
  bundle: true,
  platform: 'node',
  // The repo is ESM ("type": "module"), and so is the function.
  format: 'esm',
  target: 'node20',
  // Everything of ours is inlined; node built-ins resolve at runtime.
  external: ['node:*'],
  legalComments: 'none',
  metafile: true,
});

const out = result.metafile.outputs['api/index.js'];
console.log(
  `api/index.js  ${(out.bytes / 1024).toFixed(1)} kB  ` +
    `(${Object.keys(out.inputs).length} modules inlined)`,
);
